import fs from 'node:fs';
const layout='src/components/portal/PortalLayout.tsx';
let s=fs.readFileSync(layout,'utf8');
const oldLoader="if (snap.exists()) setStudentFeatures((snap.data() as any).featureAccess || {});";
const newLoader="if (snap.exists()) { const features=(snap.data() as any).featureAccess || {}; setStudentFeatures(features); sessionStorage.setItem('studentEdgeClubEnabled', String(features.edgeClub === true)); }";
if(!s.includes(oldLoader)) throw new Error('Portal feature loader not found');
s=s.replace(oldLoader,newLoader);
const assessment="...(studentFeatures.assessments ? [{ name: 'Assessments & Quizzes', path: '/portal/student/assessments', icon: <ClipboardCheck size={18} />, desc: 'CBT assessments & quizzes' }] : [])";
if(!s.includes(assessment)) throw new Error('Assessment gate not found');
s=s.replace(assessment, `${assessment},\n        ...(studentFeatures.edgeClub ? [{ name: 'Edge Club', path: '/portal/student/edge-club', icon: <Sparkles size={18} />, desc: 'Enabled Edge Club workspace' }] : [])`);
s=s.replace("  Users, ShieldCheck, FileCheck2, Library, SlidersHorizontal, WalletCards,", "  Users, ShieldCheck, FileCheck2, Library, SlidersHorizontal, WalletCards, Sparkles,");
fs.writeFileSync(layout,s,'utf8');

